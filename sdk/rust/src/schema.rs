//! Export a language-neutral application interface from native Serde DTOs.
//! Use this in `examples/tako_schema.rs`; `tako gen` runs that exporter.
use schemars::{
    JsonSchema,
    generate::{SchemaGenerator, SchemaSettings},
};
use serde_json::{Map, Value, json};

pub struct Application {
    app: String,
    input: SchemaGenerator,
    output: SchemaGenerator,
    primitives: Vec<Value>,
}

impl Application {
    pub fn new(app: impl Into<String>) -> Self {
        Self {
            app: app.into(),
            input: SchemaSettings::draft2020_12()
                .for_deserialize()
                .into_generator(),
            output: SchemaSettings::draft2020_12()
                .for_serialize()
                .into_generator(),
            primitives: Vec::new(),
        }
    }
    pub fn handler<I: JsonSchema, O: JsonSchema>(mut self, name: &str) -> Self {
        let input = self.input.subschema_for::<I>().to_value();
        let result = self.output.subschema_for::<O>().to_value();
        self.primitives.push(json!({"kind":"handler","name":name,"input":namespace(input,"Input"),"result":namespace(result,"Output")}));
        self
    }
    pub fn workflow<P: JsonSchema, R: JsonSchema>(mut self, name: &str) -> Self {
        let payload = self.input.subschema_for::<P>().to_value();
        let result = self.output.subschema_for::<R>().to_value();
        self.primitives.push(json!({"kind":"workflow","name":name,"payload":namespace(payload,"Input"),"result":namespace(result,"Output")}));
        self
    }
    /// M is an object whose properties map message names to their payload DTOs.
    pub fn channel<P: JsonSchema, M: JsonSchema>(mut self, name: &str) -> Self {
        let params = self.input.subschema_for::<P>().to_value();
        let messages = self.input.subschema_for::<M>().to_value();
        self.primitives.push(json!({"kind":"channel","name":name,"params":namespace(params,"Input"),"messages":namespace(messages,"Input")}));
        self
    }
    pub fn finish(mut self) -> Value {
        let mut definitions = Map::new();
        for (prefix, generator) in [("Input", &mut self.input), ("Output", &mut self.output)] {
            for (key, value) in generator.take_definitions(true) {
                definitions.insert(format!("{prefix}{key}"), namespace(value, prefix));
            }
        }
        json!({"$schema":"https://json-schema.org/draft/2020-12/schema","$comment":"Generated by tako gen. Do not edit.","$defs":definitions,"x-tako":{"version":1,"app":self.app,"primitives":self.primitives}})
    }
    pub fn print(self) -> Result<(), serde_json::Error> {
        serde_json::to_writer(std::io::stdout().lock(), &self.finish())
    }
}

fn namespace(mut value: Value, prefix: &str) -> Value {
    match &mut value {
        Value::Object(map) => {
            for (key, value) in map.iter_mut() {
                if key == "$ref"
                    && let Some(reference) = value.as_str().and_then(|s| s.strip_prefix("#/$defs/"))
                {
                    *value = Value::String(format!("#/$defs/{prefix}{reference}"));
                } else {
                    *value = namespace(value.take(), prefix);
                }
            }
        }
        Value::Array(values) => {
            for value in values {
                *value = namespace(value.take(), prefix);
            }
        }
        _ => {}
    }
    value
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde::{Deserialize, Serialize};
    #[derive(JsonSchema, Serialize, Deserialize)]
    struct Input {
        user_id: String,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        note: Option<String>,
    }
    #[test]
    fn serde_wire_names_presence_and_separate_contracts() {
        let schema = Application::new("users")
            .handler::<Input, Input>("lookup")
            .finish();
        assert_eq!(
            schema["x-tako"]["primitives"][0]["input"]["$ref"],
            "#/$defs/InputInput"
        );
        assert!(schema["$defs"]["InputInput"]["properties"]["note"].is_object());
        assert!(schema["$defs"].get("OutputInput").is_some());
    }
}
