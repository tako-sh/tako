use serde::{Deserialize, Serialize};
use serde_json::Value;
use std::collections::{BTreeMap, BTreeSet};
use std::io;

pub const COMMENT: &str = "Generated by tako gen. Do not edit.";
pub const DIALECT: &str = "https://json-schema.org/draft/2020-12/schema";

#[derive(Clone, Debug, Deserialize, Serialize)]
pub struct Manifest {
    #[serde(rename = "$schema")]
    pub dialect: String,
    #[serde(rename = "$comment", default)]
    pub comment: String,
    #[serde(rename = "$defs", default)]
    pub definitions: BTreeMap<String, Value>,
    #[serde(rename = "x-tako")]
    pub tako: Interface,
}

#[derive(Clone, Debug, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Interface {
    pub version: u32,
    pub app: String,
    pub primitives: Vec<Primitive>,
}

#[derive(Clone, Debug, Deserialize, Serialize)]
#[serde(tag = "kind", rename_all = "lowercase", deny_unknown_fields)]
pub enum Primitive {
    Handler {
        name: String,
        input: Value,
        result: Value,
    },
    Workflow {
        name: String,
        payload: Value,
        result: Value,
    },
    Channel {
        name: String,
        params: Value,
        messages: Value,
    },
}

impl Primitive {
    pub fn name(&self) -> &str {
        match self {
            Self::Handler { name, .. }
            | Self::Workflow { name, .. }
            | Self::Channel { name, .. } => name,
        }
    }
    pub fn kind(&self) -> &'static str {
        match self {
            Self::Handler { .. } => "Handler",
            Self::Workflow { .. } => "Workflow",
            Self::Channel { .. } => "Channel",
        }
    }
    pub fn fields(&self) -> [(&'static str, &Value); 2] {
        match self {
            Self::Handler { input, result, .. } => [("input", input), ("result", result)],
            Self::Workflow {
                payload, result, ..
            } => [("payload", payload), ("result", result)],
            Self::Channel {
                params, messages, ..
            } => [("params", params), ("messages", messages)],
        }
    }
}

impl Manifest {
    pub fn empty(app: String) -> Self {
        Self {
            dialect: DIALECT.into(),
            comment: COMMENT.into(),
            definitions: BTreeMap::new(),
            tako: Interface {
                version: 1,
                app,
                primitives: Vec::new(),
            },
        }
    }
    pub fn validate(&self) -> io::Result<()> {
        if self.dialect != DIALECT || self.tako.version != 1 {
            return Err(invalid(
                "unsupported Tako schema version or JSON Schema dialect",
            ));
        }
        let app = &self.tako.app;
        if app.is_empty()
            || app.len() > 63
            || !app.as_bytes()[0].is_ascii_lowercase()
            || app.ends_with('-')
            || !app
                .bytes()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == b'-')
        {
            return Err(invalid("invalid schema app name"));
        }
        let mut names = BTreeSet::new();
        for primitive in &self.tako.primitives {
            if !tako_core::network::valid_primitive_name(primitive.name())
                || !names.insert((primitive.kind(), primitive.name()))
            {
                return Err(invalid("invalid or duplicate schema primitive name"));
            }
        }
        Ok(())
    }
    pub fn reference(&self, reference: &str) -> io::Result<&Value> {
        let name = reference.strip_prefix("#/$defs/").filter(|name| !name.contains('/')).ok_or_else(|| invalid("schema references must point into this file's $defs; external references are not fetched"))?;
        let name = name.replace("~1", "/").replace("~0", "~");
        self.definitions
            .get(&name)
            .ok_or_else(|| invalid(format!("unresolved schema reference {reference}")))
    }
    pub fn dereference<'a>(&'a self, mut schema: &'a Value) -> io::Result<&'a Value> {
        let mut visited = BTreeSet::new();
        while let Some(reference) = schema.get("$ref").and_then(Value::as_str) {
            if !visited.insert(reference) {
                return Err(invalid("cyclic schema alias"));
            }
            schema = self.reference(reference)?;
        }
        Ok(schema)
    }
}

pub fn invalid(message: impl Into<String>) -> io::Error {
    io::Error::new(io::ErrorKind::InvalidData, message.into())
}
pub fn pascal(value: &str) -> String {
    let mut result = String::new();
    let mut upper = true;
    for c in value.chars() {
        if !c.is_ascii_alphanumeric() {
            upper = true;
            continue;
        }
        if result.is_empty() && c.is_ascii_digit() {
            result.push('N');
        }
        result.push(if upper { c.to_ascii_uppercase() } else { c });
        upper = false;
    }
    if result.is_empty() {
        "Value".into()
    } else {
        result
    }
}
pub fn snake(value: &str) -> String {
    let mut result = String::new();
    for (i, c) in value.chars().enumerate() {
        if !c.is_ascii_alphanumeric() {
            if !result.ends_with('_') {
                result.push('_');
            }
            continue;
        }
        if c.is_ascii_uppercase() && i > 0 && !result.ends_with('_') {
            result.push('_');
        }
        result.push(c.to_ascii_lowercase());
    }
    let mut result = result.trim_matches('_').to_string();
    if result.is_empty() || result.as_bytes()[0].is_ascii_digit() {
        result.insert_str(0, "value_");
    }
    if [
        "type", "self", "super", "crate", "mod", "match", "ref", "move", "pub", "fn", "use",
        "struct", "enum", "impl", "trait", "where", "async", "await", "loop", "in", "for", "if",
        "else", "const", "static", "dyn", "unsafe", "extern", "return", "break", "continue",
        "true", "false", "let", "mut", "as", "box", "yield", "try", "gen", "abstract", "become",
        "do", "final", "macro", "override", "priv", "typeof", "unsized", "virtual",
    ]
    .contains(&result.as_str())
    {
        result.push('_');
    }
    result
}
