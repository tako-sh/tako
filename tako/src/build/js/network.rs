use super::*;

pub(super) struct GeneratedNetworkTypes {
    pub declarations: String,
    pub contracts: String,
    pub imports: String,
    pub schema: String,
    pub resolved: crate::build::schemas::Resolved,
}

pub(super) fn generate(
    project: &Path,
    app_root: &str,
    declarations: &Path,
    command: &impl Fn() -> Command,
    config: Option<&TakoToml>,
    update: bool,
) -> std::io::Result<Option<GeneratedNetworkTypes>> {
    let root = js_app_root_dir(project, app_root);
    let declaration_dir = declarations.parent().unwrap_or(project);
    let loaded = config
        .is_none()
        .then(|| TakoToml::load_from_dir(project).ok())
        .flatten();
    let Some(config) = config.or(loaded.as_ref()) else {
        return Ok(None);
    };
    let Some(app) = &config.name else {
        return Ok(None);
    };
    let resolved = crate::build::schemas::resolve(project, &config.schemas, update)?;
    if resolved
        .manifests
        .iter()
        .any(|schema| &schema.tako.app == app)
    {
        return Err(std::io::Error::other(
            "schemas cannot import the current app",
        ));
    }
    let imports = crate::build::schemas::typescript(&resolved.manifests)?;
    let imports_path = declaration_dir.join("tako.imports.ts");
    if let Ok(previous) = fs::read_to_string(&imports_path)
        && !previous.starts_with("// Generated by tako gen.")
    {
        return Err(std::io::Error::other(
            "tako.imports.ts is now generated. Move its dependencies to `schemas` in tako.toml, then remove the handwritten file and run tako gen.",
        ));
    }
    // New/ordinary HTTP apps have no network types to inspect. In particular,
    // init must work before an SDK/compiler installation is available.
    if resolved.manifests.is_empty()
        && !["channels", "workflows", "network-handlers"]
            .iter()
            .any(|dir| root.join(dir).is_dir())
    {
        return Ok(Some(GeneratedNetworkTypes {
            declarations: ["Workflows", "Channels", "Handlers"].iter().map(|kind|format!("export interface TakoNetwork{kind} {{\n\n}}")).collect::<Vec<_>>().join("\n\n"),
            contracts: "/** AUTO-GENERATED BY TAKO — DO NOT EDIT. Publish this file through your own package. */\n\n\n\n\nexport {};\n".into(),
            imports,
            schema: serde_json::to_string_pretty(&crate::build::schemas::Manifest::empty(app.clone()))? + "\n",
            resolved,
        }));
    }
    let source = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .join("sdk/javascript/bin/gen-network-types.ts");
    let mut generator = command();
    if source.is_file() {
        generator.arg(source);
    } else {
        generator.arg("run").arg("tako-sh-gen-network-types");
    }
    let mut process = generator
        .arg(&root)
        .arg(declaration_dir)
        .arg(app)
        .current_dir(project)
        .stdin(std::process::Stdio::piped())
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::piped())
        .spawn()?;
    use std::io::Write;
    process
        .stdin
        .take()
        .unwrap()
        .write_all(serde_json::to_string(&serde_json::json!({"imports": imports}))?.as_bytes())?;
    let output = process.wait_with_output()?;
    if !output.status.success() {
        return Err(std::io::Error::other(format!(
            "network type generation failed: {}",
            String::from_utf8_lossy(&output.stderr).trim()
        )));
    }
    #[derive(serde::Deserialize)]
    struct Generated {
        declarations: String,
        contracts: String,
        schema: crate::build::schemas::Manifest,
    }
    let generated: Generated = serde_json::from_slice(&output.stdout)?;
    generated.schema.validate()?;
    Ok(Some(GeneratedNetworkTypes {
        declarations: generated.declarations,
        contracts: generated.contracts,
        imports,
        schema: serde_json::to_string_pretty(&generated.schema)? + "\n",
        resolved,
    }))
}
