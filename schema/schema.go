// Package schema exports Tako's language-neutral interface from Go JSON DTOs.
// Place the exporter in tako-schema/main.go; tako gen runs it automatically.
package schema

import (
	"encoding"
	"encoding/json"
	"fmt"
	"io"
	"reflect"
	"strings"
	"time"
)

type Application struct {
	name        string
	definitions map[string]any
	names       map[reflect.Type]string
	used        map[string]reflect.Type
	primitives  []any
	err         error
}

func New(name string) *Application {
	return &Application{name: name, definitions: map[string]any{}, names: map[reflect.Type]string{}, used: map[string]reflect.Type{}, primitives: []any{}}
}

func Handler[I, O any](app *Application, name string) {
	app.primitives = append(app.primitives, map[string]any{"kind": "handler", "name": name, "input": app.describe(reflect.TypeOf((*I)(nil)).Elem()), "result": app.describe(reflect.TypeOf((*O)(nil)).Elem())})
}
func Workflow[P, R any](app *Application, name string) {
	app.primitives = append(app.primitives, map[string]any{"kind": "workflow", "name": name, "payload": app.describe(reflect.TypeOf((*P)(nil)).Elem()), "result": app.describe(reflect.TypeOf((*R)(nil)).Elem())})
}

// Channel's M is a struct whose JSON fields map message names to payload DTOs.
func Channel[P, M any](app *Application, name string) {
	app.primitives = append(app.primitives, map[string]any{"kind": "channel", "name": name, "params": app.describe(reflect.TypeOf((*P)(nil)).Elem()), "messages": app.describe(reflect.TypeOf((*M)(nil)).Elem())})
}
func (a *Application) Write(w io.Writer) error {
	if a.err != nil {
		return a.err
	}
	encoder := json.NewEncoder(w)
	encoder.SetIndent("", "  ")
	return encoder.Encode(map[string]any{"$schema": "https://json-schema.org/draft/2020-12/schema", "$comment": "Generated by tako gen. Do not edit.", "$defs": a.definitions, "x-tako": map[string]any{"version": 1, "app": a.name, "primitives": a.primitives}})
}
func (a *Application) fail(format string, args ...any) any {
	if a.err == nil {
		a.err = fmt.Errorf(format, args...)
	}
	return false
}

var rawType = reflect.TypeOf(json.RawMessage{})
var timeType = reflect.TypeOf(time.Time{})
var marshalerType = reflect.TypeOf((*json.Marshaler)(nil)).Elem()
var textMarshalerType = reflect.TypeOf((*encoding.TextMarshaler)(nil)).Elem()

func customMarshaler(t reflect.Type) bool {
	return t.Implements(marshalerType) || reflect.PointerTo(t).Implements(marshalerType) ||
		t.Implements(textMarshalerType) || reflect.PointerTo(t).Implements(textMarshalerType)
}

func (a *Application) describe(t reflect.Type) any {
	if a.err != nil {
		return false
	}
	if t == rawType {
		return true
	}
	if t == timeType {
		return map[string]any{"type": "string", "format": "date-time"}
	}
	if t.Kind() == reflect.Pointer {
		return map[string]any{"anyOf": []any{a.describe(t.Elem()), map[string]any{"type": "null"}}}
	}
	if customMarshaler(t) {
		return a.fail("%s has custom JSON marshaling; export a DTO with explicit JSON fields instead", t)
	}
	if prior, ok := a.names[t]; ok {
		return map[string]any{"$ref": "#/$defs/" + prior}
	}
	if t.Name() != "" && (t.Kind() == reflect.Struct || t.Kind() == reflect.Slice || t.Kind() == reflect.Array || t.Kind() == reflect.Map) {
		name := t.Name()
		if prior, ok := a.used[name]; ok && prior != t {
			return a.fail("duplicate schema type name %s", name)
		}
		if len(a.definitions) >= 4096 {
			return a.fail("too many schema definitions")
		}
		a.used[name] = t
		a.names[t] = name
		a.definitions[name] = false
		a.definitions[name] = a.shape(t)
		return map[string]any{"$ref": "#/$defs/" + name}
	}
	return a.shape(t)
}
func (a *Application) shape(t reflect.Type) any {
	switch t.Kind() {
	case reflect.Bool:
		return map[string]any{"type": "boolean"}
	case reflect.String:
		return map[string]any{"type": "string"}
	case reflect.Float32, reflect.Float64:
		return map[string]any{"type": "number"}
	case reflect.Int8, reflect.Int16, reflect.Int32:
		bits := t.Bits()
		return map[string]any{"type": "integer", "minimum": -(int64(1) << (bits - 1)), "maximum": (int64(1) << (bits - 1)) - 1}
	case reflect.Uint8, reflect.Uint16, reflect.Uint32:
		return map[string]any{"type": "integer", "minimum": 0, "maximum": (uint64(1) << t.Bits()) - 1}
	case reflect.Int, reflect.Int64, reflect.Uint, reflect.Uint64, reflect.Uintptr:
		return a.fail("%s can exceed JavaScript's safe integer range; use json:\",string\" on the field or a decimal-string DTO", t)
	case reflect.Interface:
		if t.NumMethod() != 0 {
			return a.fail("cannot export non-empty interface %s", t)
		}
		return true
	case reflect.Slice:
		if t.Elem().Kind() == reflect.Uint8 {
			return map[string]any{"anyOf": []any{map[string]any{"type": "string", "contentEncoding": "base64"}, map[string]any{"type": "null"}}}
		}
		return map[string]any{"anyOf": []any{map[string]any{"type": "array", "items": a.describe(t.Elem())}, map[string]any{"type": "null"}}}
	case reflect.Array:
		if t.Len() > 4096 {
			return a.fail("fixed array too large")
		}
		items := make([]any, t.Len())
		for i := range items {
			items[i] = a.describe(t.Elem())
		}
		shape := map[string]any{"type": "array", "minItems": t.Len(), "maxItems": t.Len(), "items": false}
		if len(items) > 0 {
			shape["prefixItems"] = items
		}
		return shape
	case reflect.Map:
		if t.Key().Kind() != reflect.String {
			return a.fail("JSON map keys must be strings: %s", t)
		}
		return map[string]any{"anyOf": []any{map[string]any{"type": "object", "additionalProperties": a.describe(t.Elem())}, map[string]any{"type": "null"}}}
	case reflect.Struct:
		properties := map[string]any{}
		required := []string{}
		for i := 0; i < t.NumField(); i++ {
			field := t.Field(i)
			if field.PkgPath != "" {
				continue
			}
			tag := strings.Split(field.Tag.Get("json"), ",")
			name := tag[0]
			if name == "-" {
				continue
			}
			if name == "" {
				name = field.Name
			}
			if field.Anonymous {
				return a.fail("embedded JSON fields require an explicit DTO: %s.%s", t, field.Name)
			}
			if _, ok := properties[name]; ok {
				return a.fail("duplicate JSON field %s", name)
			}
			optional, stringValue := false, false
			for _, option := range tag[1:] {
				if option == "omitempty" {
					optional = true
				}
				if option == "string" {
					stringValue = true
				}
				if option == "omitzero" {
					return a.fail("omitzero needs an explicit DTO schema; use omitempty")
				}
			}
			if stringValue {
				valueType := field.Type
				nullable := valueType.Kind() == reflect.Pointer
				if nullable {
					valueType = valueType.Elem()
				}
				if customMarshaler(valueType) {
					return a.fail("%s has custom JSON marshaling; export a DTO with explicit JSON fields instead", valueType)
				}
				switch valueType.Kind() {
				case reflect.String, reflect.Bool, reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64, reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Float32, reflect.Float64:
				default:
					return a.fail("json string tag on unsupported type %s", valueType)
				}
				var value any = map[string]any{"type": "string"}
				if nullable {
					value = map[string]any{"anyOf": []any{value, map[string]any{"type": "null"}}}
				}
				properties[name] = value
			} else {
				properties[name] = a.describe(field.Type)
			}
			if !optional {
				required = append(required, name)
			}
		}
		return map[string]any{"type": "object", "properties": properties, "required": required, "additionalProperties": false}
	default:
		return a.fail("unsupported JSON type %s", t)
	}
}
